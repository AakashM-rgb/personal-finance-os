"""One invocation of a data-correction migration, in either direction.

Written only by migrations (today: `c8e4a1f6b2d9`, the F-001 credit-card
balance correction) and read only by their own safeguards. No service,
repository or endpoint touches it, and it holds no user data -- which is why
there is no `user_id` and no FK.

It exists because a correction that is only safe to apply once needs a record
that says it has already run, and that record must outlive `audit_logs`: the
same facts go into an audit row, but a retention job, a manual cleanup or a
partial restore could remove those, and the migration would then silently
re-apply a correction it had already made. The migration reads whichever of
the two records is older, so one surviving source is enough.

Nothing may prune this table, and `downgrade()` deliberately does not drop it:
a reverted correction still happened, and the next upgrade needs to know. It
is declared here so the schema has one source of truth and an autogenerated
migration never proposes dropping it.
"""

from datetime import datetime
from typing import Any

from sqlalchemy import DateTime, Index, String, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column

from app.core.database import Base
from app.models.base import UUIDPrimaryKeyMixin


class DataCorrectionRun(UUIDPrimaryKeyMixin, Base):
    __tablename__ = "data_correction_runs"
    __table_args__ = (
        Index("ix_data_correction_runs_revision_ran_at", "revision", "ran_at"),
    )

    revision: Mapped[str] = mapped_column(String(32), nullable=False)
    direction: Mapped[str] = mapped_column(String(16), nullable=False)
    mode: Mapped[str] = mapped_column(String(16), nullable=False)
    ran_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True), server_default=func.now(), nullable=False
    )
    details: Mapped[dict[str, Any]] = mapped_column(
        JSONB, server_default=text("'{}'::jsonb"), nullable=False
    )
